"""The icon files and the application icon, checked without Qt.

Why this exists
    The icons are tinted by replacing `currentColor` before they are drawn, so
    an SVG exported with a hard-coded colour would stay black on the dark
    theme and nobody would notice until a screenshot. The .ico is generated by
    `scripts/make_icons.py`, and an .ico missing the small sizes is drawn by
    Windows as a blurry downscale in the title bar and on the taskbar.
"""

from __future__ import annotations

import struct
import xml.etree.ElementTree as ElementTree
from pathlib import Path

import pytest

ASSETS = Path(__file__).resolve().parents[1] / "src" / "aynthor" / "ui" / "assets"
ICONS = sorted((ASSETS / "icons").glob("*.svg"))


def test_there_are_icons():
    assert len(ICONS) >= 10


@pytest.mark.parametrize("path", ICONS, ids=[p.stem for p in ICONS])
def test_every_icon_is_valid_svg_drawn_in_the_current_colour(path: Path):
    text = path.read_text(encoding="utf-8")
    root = ElementTree.fromstring(text)
    assert root.tag.endswith("svg")
    assert root.get("viewBox") == "0 0 24 24"
    assert "currentColor" in text
    assert "#" not in text, "a hard-coded colour would not follow the theme"


def test_the_application_icon_has_every_size_windows_asks_for():
    data = (ASSETS / "app.ico").read_bytes()
    reserved, kind, count = struct.unpack("<HHH", data[:6])
    assert (reserved, kind) == (0, 1)
    sizes = []
    for index in range(count):
        width, _height, _colours, _zero, _planes, _bpp, length, offset = struct.unpack(
            "<BBBBHHII", data[6 + 16 * index: 22 + 16 * index])
        sizes.append(width or 256)
        assert data[offset:offset + 8] == b"\x89PNG\r\n\x1a\n"
        assert offset + length <= len(data)
    assert {16, 24, 32, 48, 256} <= set(sizes)


def test_both_logo_drawings_exist():
    for name in ("logo.svg", "logo-small.svg"):
        root = ElementTree.fromstring((ASSETS / name).read_text(encoding="utf-8"))
        assert root.get("viewBox") == "0 0 256 256"
